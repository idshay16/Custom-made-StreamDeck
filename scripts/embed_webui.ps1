<#
.SYNOPSIS
  Gzip webui/* into firmware/streamdeck/webui_assets.h (C byte arrays).
  Run after editing anything in webui/. build.ps1 runs it automatically for
  firmware\streamdeck. The generated header is committed so Arduino IDE
  builds work without running this.
#>
$ErrorActionPreference = 'Stop'
$Repo = Split-Path -Parent $PSScriptRoot
$Src  = Join-Path $Repo 'webui'
$Out  = Join-Path $Repo 'firmware\streamdeck\webui_assets.h'

$types = @{ '.html' = 'text/html'; '.js' = 'application/javascript'; '.css' = 'text/css'; '.svg' = 'image/svg+xml'; '.png' = 'image/png'; '.ico' = 'image/x-icon' }

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// GENERATED by scripts/embed_webui.ps1 from webui/. Do not edit.')
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('#include <stdint.h>')
[void]$sb.AppendLine('#include <stddef.h>')
[void]$sb.AppendLine('struct WebAsset { const char *path; const char *type; const uint8_t *data; size_t len; };')

$entries = @()
$i = 0
$total = 0
foreach ($f in Get-ChildItem $Src -File | Sort-Object Name) {
  $raw = [IO.File]::ReadAllBytes($f.FullName)
  $ms = [IO.MemoryStream]::new()
  $gz = [IO.Compression.GZipStream]::new($ms, [IO.Compression.CompressionLevel]::Optimal)
  $gz.Write($raw, 0, $raw.Length)
  $gz.Dispose()
  $bytes = $ms.ToArray()
  $total += $bytes.Length
  [void]$sb.AppendLine("// $($f.Name): $($raw.Length) -> $($bytes.Length) bytes")
  [void]$sb.Append("static const uint8_t ASSET_$i[] = {")
  for ($b = 0; $b -lt $bytes.Length; $b++) {
    if ($b % 24 -eq 0) { [void]$sb.Append("`n  ") }
    [void]$sb.Append('0x{0:x2},' -f $bytes[$b])
  }
  [void]$sb.AppendLine("`n};")
  $type = $types[$f.Extension.ToLower()]
  if (-not $type) { $type = 'application/octet-stream' }
  $entries += "  {`"/$($f.Name)`", `"$type`", ASSET_$i, sizeof(ASSET_$i)},"
  $i++
}
[void]$sb.AppendLine('static const WebAsset WEB_ASSETS[] = {')
foreach ($e in $entries) { [void]$sb.AppendLine($e) }
[void]$sb.AppendLine('};')
[void]$sb.AppendLine("static const size_t WEB_ASSET_COUNT = $i;")

$new = $sb.ToString()
$old = if (Test-Path $Out) { [IO.File]::ReadAllText($Out) } else { '' }
if ($new -ne $old) {
  [IO.File]::WriteAllText($Out, $new)
  Write-Host "webui: $i files, $total bytes gzipped -> $Out"
} else {
  Write-Host "webui: unchanged"
}
